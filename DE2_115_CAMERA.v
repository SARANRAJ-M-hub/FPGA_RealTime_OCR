wire w_BIN_PIXEL = (oVGA_G < DARK_THRESHOLD) ? 1'b1 : 1'b0;

Detector u_detect (
    .clk(VGA_CTRL_CLK),
    .rst_n(DLY_RST_2),
    .VGA_VS(w_VGA_VS),
    .VGA_HS(w_VGA_HS),
    .x_coord(w_H_Cont),
    .y_coord(w_V_Cont),
    .pixel_is_black(w_BIN_PIXEL),
    .iPAUSE(SNAPSHOT_BTN),
    .iALPHA_MODE(ALPHA_MODE),
    
    .X_MIN0(w_X_MIN0), .X_MAX0(w_X_MAX0), .Y_MIN0(w_Y_MIN0), .Y_MAX0(w_Y_MAX0),
    .X_MIN1(w_X_MIN1), .X_MAX1(w_X_MAX1), .Y_MIN1(w_Y_MIN1), .Y_MAX1(w_Y_MAX1),
    .X_MIN2(w_X_MIN2), .X_MAX2(w_X_MAX2), .Y_MIN2(w_Y_MIN2), .Y_MAX2(w_Y_MAX2),
    .X_MIN3(w_X_MIN3), .X_MAX3(w_X_MAX3), .Y_MIN3(w_Y_MIN3), .Y_MAX3(w_Y_MAX3),
    .X_MIN4(w_X_MIN4), .X_MAX4(w_X_MAX4), .Y_MIN4(w_Y_MIN4), .Y_MAX4(w_Y_MAX4),
    .oCHAR_COUNT(w_CHAR_COUNT),
    .oCHAR0(w_CHAR0),
    .oCHAR1(w_CHAR1),
    .oCHAR2(w_CHAR2),
    .oCHAR3(w_CHAR3),
    .oCHAR4(w_CHAR4),
    .oOSD_BG(w_OSD_BG),
    .oOSD_TEXT(w_OSD_TEXT),
    .oOSD_GRID_ON(w_OSD_GRID_ON),
    .oOSD_GRID_OFF(w_OSD_GRID_OFF)
);

// ========================================================
// VGA OUTPUT MULTIPLEXER (CORNER OSD + 5 GREEN BOXES)
// ========================================================

wire box0_edge = (w_X_MAX0 > w_X_MIN0) && (
                 (((w_H_Cont >= w_X_MIN0 && w_H_Cont <= w_X_MIN0 + 13'd2) || (w_H_Cont <= w_X_MAX0 && w_H_Cont + 13'd2 >= w_X_MAX0)) && (w_V_Cont >= w_Y_MIN0 && w_V_Cont <= w_Y_MAX0)) || 
                 (((w_V_Cont >= w_Y_MIN0 && w_V_Cont <= w_Y_MIN0 + 13'd2) || (w_V_Cont <= w_Y_MAX0 && w_V_Cont + 13'd2 >= w_Y_MAX0)) && (w_H_Cont >= w_X_MIN0 && w_H_Cont <= w_X_MAX0)));

wire box1_edge = (w_X_MAX1 > w_X_MIN1) && (
                 (((w_H_Cont >= w_X_MIN1 && w_H_Cont <= w_X_MIN1 + 13'd2) || (w_H_Cont <= w_X_MAX1 && w_H_Cont + 13'd2 >= w_X_MAX1)) && (w_V_Cont >= w_Y_MIN1 && w_V_Cont <= w_Y_MAX1)) || 
                 (((w_V_Cont >= w_Y_MIN1 && w_V_Cont <= w_Y_MIN1 + 13'd2) || (w_V_Cont <= w_Y_MAX1 && w_V_Cont + 13'd2 >= w_Y_MAX1)) && (w_H_Cont >= w_X_MIN1 && w_H_Cont <= w_X_MAX1)));

wire box2_edge = (w_X_MAX2 > w_X_MIN2) && (
                 (((w_H_Cont >= w_X_MIN2 && w_H_Cont <= w_X_MIN2 + 13'd2) || (w_H_Cont <= w_X_MAX2 && w_H_Cont + 13'd2 >= w_X_MAX2)) && (w_V_Cont >= w_Y_MIN2 && w_V_Cont <= w_Y_MAX2)) || 
                 (((w_V_Cont >= w_Y_MIN2 && w_V_Cont <= w_Y_MIN2 + 13'd2) || (w_V_Cont <= w_Y_MAX2 && w_V_Cont + 13'd2 >= w_Y_MAX2)) && (w_H_Cont >= w_X_MIN2 && w_H_Cont <= w_X_MAX2)));

wire box3_edge = (w_X_MAX3 > w_X_MIN3) && (
                 (((w_H_Cont >= w_X_MIN3 && w_H_Cont <= w_X_MIN3 + 13'd2) || (w_H_Cont <= w_X_MAX3 && w_H_Cont + 13'd2 >= w_X_MAX3)) && (w_V_Cont >= w_Y_MIN3 && w_V_Cont <= w_Y_MAX3)) || 
                 (((w_V_Cont >= w_Y_MIN3 && w_V_Cont <= w_Y_MIN3 + 13'd2) || (w_V_Cont <= w_Y_MAX3 && w_V_Cont + 13'd2 >= w_Y_MAX3)) && (w_H_Cont >= w_X_MIN3 && w_H_Cont <= w_X_MAX3)));

wire box4_edge = (w_X_MAX4 > w_X_MIN4) && (
                 (((w_H_Cont >= w_X_MIN4 && w_H_Cont <= w_X_MIN4 + 13'd2) || (w_H_Cont <= w_X_MAX4 && w_H_Cont + 13'd2 >= w_X_MAX4)) && (w_V_Cont >= w_Y_MIN4 && w_V_Cont <= w_Y_MAX4)) || 
                 (((w_V_Cont >= w_Y_MIN4 && w_V_Cont <= w_Y_MIN4 + 13'd2) || (w_V_Cont <= w_Y_MAX4 && w_V_Cont + 13'd2 >= w_Y_MAX4)) && (w_H_Cont >= w_X_MIN4 && w_H_Cont <= w_X_MAX4)));

wire is_box_edge = box0_edge | box1_edge | box2_edge | box3_edge | box4_edge;

// Blue Border showing the Safe Detection Zone (X: 310..909, Y: 130..445)
wire is_safe_border = ((w_H_Cont == 13'd310 || w_H_Cont == 13'd909) && (w_V_Cont >= 13'd130 && w_V_Cont <= 13'd365)) ||
                      ((w_V_Cont == 13'd130 || w_V_Cont == 13'd365) && (w_H_Cont >= 13'd310 && w_H_Cont <= 13'd909));

wire [7:0] bw_feed = w_BIN_PIXEL ? 8'h00 : 8'hFF;

// Base video feed: SW[17] UP = B&W Threshold View, SW[17] DOWN = Live Color Camera View
wire [7:0] base_R = DETECTION_MODE ? bw_feed : oVGA_R[9:2];
wire [7:0] base_G = DETECTION_MODE ? bw_feed : oVGA_G[9:2];
wire [7:0] base_B = DETECTION_MODE ? bw_feed : oVGA_B[9:2];

// Overlay Priority:
// 1. OSD Text (Bright Yellow/Red)
// 2. OSD 5x5 Active Grid Cell (Bright Cyan)
// 3. OSD 5x5 Inactive Grid Cell (Dark Gray-Blue)
// 4. OSD Background Box (Dark Navy)
// 5. Green Bounding Boxes
// 6. Blue Safe Zone Border
assign VGA_R = w_OSD_TEXT     ? 8'hFF :
               w_OSD_GRID_ON  ? 8'h00 :
               w_OSD_GRID_OFF ? 8'h28 :
               w_OSD_BG       ? 8'h10 :
               is_box_edge    ? 8'h00 :
               is_safe_border ? 8'h00 : base_R;

assign VGA_G = w_OSD_TEXT     ? (w_OSD_BG ? 8'hFF : 8'h00) :
               w_OSD_GRID_ON  ? 8'hFF :
               w_OSD_GRID_OFF ? 8'h28 :
               w_OSD_BG       ? 8'h10 :
               is_box_edge    ? 8'hFF :
               is_safe_border ? 8'h00 : base_G;

assign VGA_B = w_OSD_TEXT     ? 8'h00 :
               w_OSD_GRID_ON  ? 8'hFF :
               w_OSD_GRID_OFF ? 8'h40 :
               w_OSD_BG       ? 8'h20 :
               is_box_edge    ? 8'h00 :
               is_safe_border ? 8'hFF : base_B;

assign VGA_HS = w_VGA_HS;
assign VGA_VS = w_VGA_VS;
assign VGA_BLANK_N = w_VGA_BLANK_N;

// =======================================================
//  7-SEGMENT DISPLAYS (HEX0 = Box Count, HEX7:4 = Box 0 Coords)
// =======================================================
SEG7_LUT u_hex0 (.oSEG(HEX0), .iDIG(w_CHAR_COUNT));
assign HEX1 = 7'b1111111;
assign HEX2 = 7'b1111111;
assign HEX3 = 7'b1111111;
SEG7_LUT u_hex4 (.oSEG(HEX4), .iDIG(w_Y_MIN0[5:2]));
SEG7_LUT u_hex5 (.oSEG(HEX5), .iDIG(w_Y_MIN0[9:6]));
SEG7_LUT u_hex6 (.oSEG(HEX6), .iDIG(w_X_MIN0[5:2]));
SEG7_LUT u_hex7 (.oSEG(HEX7), .iDIG(w_X_MIN0[9:6]));

